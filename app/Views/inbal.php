            <section class="inbal">
                <h2>Instituto Nacional de Bellas Artes y Literatura</h2>
                <p>El INBAL es un organismo cultural del gobierno mexicano responsable de estimular la producción artística, promover la difusión de las artes y organizar la educación artística en todo el territorio nacional.</p>
                <p>Su MISIÓN es difundir y divulgar las artes, el patrimonio artístico nacional, y la educación y la investigación artística.</p>
                <p>Su VISIÓN es consolidarse como una institución con vocación nacional responsable de la difusión de los derechos culturales de todos los mexicanos. Se guía bajo los principios de la equidad de género, igualdad, diversidad e inclusión, y trabaja en torno a la memoria, lengua y pueblos originarios, diplomacia cultural, innovación, migración y colaboración interinstitucional.</p>
            </section>

            <section class="sgba">
                <h3>Subdirección General de Bellas Artes (SGBA)</h3>
                <p>Tanto las coordinaciones nacionales de distintas disciplinas artísticas como los grupos artísticos que forman parte del Instituto Nacional de Bellas Artes están adscritos a la SGBA. Esta instancia mantiene una relación estrecha con estos centros de trabajo (la Coordinación Nacional de Teatro, la Coordinación Nacional de Danza, la Coordinación Nacional de Música y Ópera, la Coordinación Nacional de Literatura y la Compañía Nacional de Teatro, Compañía Nacional de Danza, Centro de Producción de Danza Contemporánea, Orquesta Sinfónica Nacional, Orquesta de Cámara de Bellas Artes, Centro de Experimentación y Producción de Música Contemporánea, y la Compañía Nacional de Ópera) para armonizar y hacer las gestiones correspondientes que permitan la realización de la programación cultural y artística que desde el INBAL se ofrece a la población mexicana.</p>
                <p>Para diligenciar dicha misión, también se cuenta con un programa de Extensión Cultural (con actividades en su mayoría dirigidas a la promoción de la lectura y difusión del arte), un Programa de Diversidad e Igualdad (cuyo objetivo es promover la inclusión social de manera transversal en las acciones del Instituto, tanto a nivel interno como externo), una Dirección de Asuntos Internacionales (encargada del seguimiento a las relaciones y trámites del Instituto con el extranjero), y el manejo de recintos culturales —como el Centro Cultural del Bosque y el Palacio de Bellas Artes— que funcionan como sedes de parte de las actividades de los centros de trabajo.</p>
            </section>

            <section class="sgpai">
                <h3>Subdirección General del Patrimonio Artístico Inmueble (SGPAI)</h3>
                <p>Mediante la SGPAI, el Instituto Nacional de Bellas Artes y Literatura lleva a cabo tareas de catalogación y registro, de conservación e investigación, así como de documentación, protección y difusión de los bienes muebles e inmuebles que son parte del patrimonio nacional. El patrimonio artístico a cargo del INBAL se preserva mediante distintos proyectos coordinados por la DACPAI y el CENCROPAM, mientras que la difusión está gestionada por los museos parte de la Red INBAL y la CNAV, así como en espacios expositivos de otras instituciones nacionales e internacionales.</p>
                <p>La Dirección de Arquitectura y Conservación del Patrimonio Artístico Inmueble está abocada a la protección, promoción y difusión de la obra arquitectónica mexicana. Entre sus funciones está definir y aplicar las normas, políticas e instrumentos para la preservación del patrimonio artístico y arquitectónico, así como organizar y desarrollar el programa de Monumentos y Zonas Artísticos y sugerir aquellas que puedan ser consideradas como patrimonio artístico inmueble. El Centro Nacional de Conservación del Patrimonio Artístico Inmueble se encarga de velar por la preservación del patrimonio artístico nacional mediante el fortalecimiento y actualización de los sistemas y mecanismos de catalogación, registro, conservación y restauración, tanto en los aspectos normativos, como en los técnicos y de gestión. Dicho control se realiza a través del Sistema General de Registro de Obra Patrimonial Artística Mueble (SIGROPAM). La Coordinación Nacional de Artes Visuales desarrolla, impulsa y difunde las artes plásticas y visuales en México, por lo que colabora estrechamente con la Red de Museos INBAL (18 en total).</p>
            </section>

            <section class="sgeia">
                <h3>Subdirección General de Educación e Investigación Artística (SGEIA)</h3>
                <p>La SGEIA proporciona, desarrolla y supervisa la implementación de normas, políticas y directrices para la educación e investigación artísticas del país, basándose en un modelo educativo que toma en cuenta tanto el contexto nacional, como las necesidades de la población relativas al pleno ejercicio de los derechos culturales. A su vez, pretende impulsar la investigación artística y su desarrollo en nuestro país con el fin de proteger, preservar y difundir sus diversas manifestaciones y expresiones artísticas. Con el objetivo de cumplir con lo anterior, la SGEIA ofrece estudios en los niveles inicial, medio superior y superior, contando con 29 escuelas:</p>
                <ul>
                    <li>13 escuelas profesionales (nivel superior) enfocadas en teatro, música, danza y artes plásticas y visuales ubicadas en Querétaro, Nuevo León y Ciudad de México; </li>
                    <li>12 escuelas de nivel medio superior de arte (llamados Centro de Educación Artística, CEDART) ubicadas en diez entidades federativas (Ciudad de México, Querétaro, Oaxaca, Sonora, Michoacán, Jalisco, Yucatán, Colima, Chihuahua y Nuevo León). </li>
                    <li>Cuatro Escuelas de Iniciación Artística (nivel inicial): escuelas públicas dedicadas a desarrollar las habilidades básicas en las disciplinas de artes plásticas, música, teatro y danza en niños, jóvenes y adultos. Se ubican en la Ciudad de México.</li>
                    <li>Cuatro Centros Nacionales de Investigación, Documentación e Información (cada uno especializado en disciplinas distintas: teatro, danza, música y artes plásticas).</li>
                </ul>
                <p>La SGEIA opera con la visión de convertir a las escuelas del INBAL –en todos sus niveles–, así como a sus centros de investigación, en referentes académicos y artísticos con la capacidad de evolucionar y de adaptarse a los cambios sociales presentes tanto en el ámbito nacional, como internacional.</p>
            </section>

